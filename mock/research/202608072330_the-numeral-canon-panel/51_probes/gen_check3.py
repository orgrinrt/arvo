#!/usr/bin/env python3
"""Cross-check that calls the emitted arms, rather than reimplementing them.

`41_dispatcher_note_no_bench_here_has_ever_checked_its_answers.md` measured the
digest column zero across 214 CSVs and 82,960 rows, so nothing committed in
this repository has ever confirmed that the arms of a comparison compute the
same answer, and one arm was found doing no work at all. A cross-check that
reimplements the algorithm and compares against itself has the same defect one
level up: it certifies the generator, not the code under test.

This links the actual `#[no_mangle] extern "C"` symbols out of each width crate
and calls them on a buffer built independently, so an arm that computes nothing
fails here rather than passing quietly.

  python3 gen_check3.py <widths-dir> <out.rs>
"""

import os
import sys


def access_bytes(w):
    return (w + 7 + 7) // 8


def carrier(w):
    for bits, name in ((8, "u8"), (16, "u16"), (32, "u32"), (64, "u64")):
        if w <= bits:
            return name
    raise ValueError(w)


def main():
    wdir, out = sys.argv[1], sys.argv[2]
    elems = 1000
    widths = sorted(int(f[1:-3]) for f in os.listdir(wdir)
                    if f.startswith("w") and f.endswith(".rs"))

    decls, cases = [], []
    for w in widths:
        nbytes = (w * elems + 7) // 8 + 8
        car = carrier(w)
        for arm in ("typed", "gather", "wide", "hand"):
            decls.append(f'    fn w{w}_{arm}(p: *const u8) -> u64;')
        decls.append(f'    fn w{w}_native(p: *const {car}) -> u64;')
        cases.append(f"""
    {{
        const W: usize = {w};
        const MASK: u64 = {(1 << w) - 1};
        const BYTES: usize = {nbytes};
        let vals: Vec<u64> = (0..{elems})
            .map(|k| ((k as u64).wrapping_mul(2654435761) ^ ((k as u64) << 7)) & MASK)
            .collect();
        let mut packed = vec![0u8; BYTES];
        for (k, &v) in vals.iter().enumerate() {{
            let base = k * W;
            for i in 0..W {{
                if (v >> i) & 1 == 1 {{ packed[(base + i) / 8] |= 1 << ((base + i) % 8); }}
            }}
        }}
        let unpacked: Vec<{car}> = vals.iter().map(|&v| v as {car}).collect();
        let want = vals.iter().fold(0u64, |a, &b| a.wrapping_add(b));
        let got = unsafe {{ (
            w{w}_typed(packed.as_ptr()),
            w{w}_gather(packed.as_ptr()),
            w{w}_wide(packed.as_ptr()),
            w{w}_hand(packed.as_ptr()),
            w{w}_native(unpacked.as_ptr()),
        ) }};
        checked += 1;
        let all = [got.0, got.1, got.2, got.3, got.4];
        if all.iter().any(|&g| g != want) {{
            bad += 1;
            println!("W={{}} MISMATCH want={{}} typed={{}} gather={{}} wide={{}} hand={{}} native={{}}",
                     W, want, got.0, got.1, got.2, got.3, got.4);
        }}
        if want == 0 {{
            bad += 1;
            println!("W={{}} DEGENERATE: the reference sum is zero, so agreement proves nothing", W);
        }}
    }}""")

    src = f"""// generated by gen_check3.py. Links and calls the emitted arms.
use std::process::ExitCode;

#[link(name = "widthmatrix", kind = "static")]
unsafe extern "C" {{
{chr(10).join(decls)}
}}

fn main() -> ExitCode {{
    let mut bad = 0usize;
    let mut checked = 0usize;
{"".join(cases)}
    if bad == 0 {{
        println!("all {{checked}} widths: five arms agree with an independently built reference, \
and no reference sum is zero");
        ExitCode::SUCCESS
    }} else {{
        println!("{{bad}} failures across {{checked}} widths");
        ExitCode::FAILURE
    }}
}}
"""
    with open(out, "w") as f:
        f.write(src)
    print(f"wrote {out} covering {len(widths)} widths")


if __name__ == "__main__":
    main()
