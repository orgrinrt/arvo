#!/usr/bin/env python3
"""Decisive control: hold the gather shape fixed and sweep only the width.

The first control (gen_access_control.py) tried to separate the declared width
from the access-byte count by fixing W at 13 and raising ACCESS. It failed to
separate them, and the failure is informative: at W = 13 the result is masked
to 13 bits, so bytes beyond the third contribute nothing, the compiler proves
those loads dead and removes them, and the crate compiled at ACCESS = 8 emits
the same code as the one at ACCESS = 3. The number of LIVE access bytes is
floor((W + 14) / 8), a function of W, so the two cannot be varied
independently and no experiment inside this design can attribute the boundary
to one rather than the other.

What can be separated is the SOURCE SHAPE of the gather from the width. This
sweeps W with three gather shapes whose source is identical across every width
except for the stride multiplier and the mask:

  wN_loop8   gather written as `while i < 8`, a loop, same trip count at every
             width.
  wN_flat8   the same eight bytes spelled out flat, same at every width.
  wN_wide    one u64 load, no gather.

If the collapse follows the width with the gather shape held fixed, the gather
is not what the compiler is responding to. If it follows the shape, it is.

  python3 gen_fixed_gather.py <outdir> [elems]
"""

import os
import sys

FLAT8 = " | ".join(
    f"((b[byte + {i}] as u64) << {8 * i})" if i else "b[byte] as u64"
    for i in range(8)
)


def gen(w: int, elems: int) -> str:
    mask = (1 << w) - 1
    nbytes = (w * elems + 7) // 8 + 16
    return f"""// generated by gen_fixed_gather.py. width {w}, gather shape fixed at 8 bytes.
#![no_std]
#![allow(dead_code)]

#[cfg(link_check)]
#[panic_handler]
fn ph(_: &core::panic::PanicInfo) -> ! {{ loop {{}} }}

pub const BYTES: usize = {nbytes};
pub const ELEMS: usize = {elems};

#[repr(transparent)]
pub struct Col {{ bytes: [u8; BYTES] }}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_loop8(c: &Col) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{
        let base = k * {w};
        let byte = base / 8;
        let mut acc: u64 = 0;
        let mut i = 0;
        while i < 8 {{
            acc |= (c.bytes[byte + i] as u64) << (8 * i);
            i += 1;
        }}
        s = s.wrapping_add((acc >> (base % 8)) & {mask});
        k += 1;
    }}
    s
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_flat8(c: &Col) -> u64 {{
    let b = &c.bytes;
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{
        let base = k * {w};
        let byte = base / 8;
        let acc: u64 = {FLAT8};
        s = s.wrapping_add((acc >> (base % 8)) & {mask});
        k += 1;
    }}
    s
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_wide(c: &Col) -> u64 {{
    let b = &c.bytes;
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{
        let base = k * {w};
        let byte = base / 8;
        let mut t = [0u8; 8];
        let mut i = 0;
        while i < 8 {{ t[i] = b[byte + i]; i += 1; }}
        s = s.wrapping_add((u64::from_le_bytes(t) >> (base % 8)) & {mask});
        k += 1;
    }}
    s
}}
"""


def main():
    outdir = sys.argv[1]
    elems = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
    os.makedirs(outdir, exist_ok=True)
    widths = list(range(1, 34)) + [40, 47, 48]
    for w in widths:
        with open(os.path.join(outdir, f"w{w:02d}.rs"), "w") as f:
            f.write(gen(w, elems))
    print(f"generated {len(widths)} fixed-gather crates in {outdir}")


if __name__ == "__main__":
    main()
