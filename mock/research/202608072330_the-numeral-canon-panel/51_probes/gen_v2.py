#!/usr/bin/env python3
"""Generate a three-arm packed-walk comparison per declared width.

Supersedes gen_width_matrix.py, whose two arms were the same MIR written twice
and therefore folded to one body at every width. That fold is a true statement
about associated consts resolving before codegen and it is not the erasure
question, because nothing in it could have failed.

Three arms per width, and they are different code rather than the same code
with the constant arriving from a different place:

  wN_typed   the typestate arm. Every layout coordinate arrives as an
             associated const through a generic `Col<D>`, and the access loop
             is written generically over `D::ACCESS`.
  wN_hand    the arm a consumer writes when doing the packing themselves: the
             access is unrolled to exactly the bytes this width needs, with
             the shifts and the mask spelled as literals at the site. This is
             what "erases to exactly what you describe" has to mean, and it is
             a different source shape from the typed arm rather than a copy of
             it. `17_probes/t2_aggregate_erasure.rs` uses this shape at W=13,
             where it did not fold.
  wN_native  the competitor the packing is traded against: the same values in
             an unpacked array of the smallest native carrier that holds W
             bits, masked to W so it computes a comparable quantity. This arm
             is what a consumer gets by not packing at all, and no oracle in
             this panel has compared against it.

typed against hand is the erasure question. typed against native is the
packing question, and only its SHAPE is answerable here: what it costs is
unpriced, because pricing needs the bench harness at `mock/benches/` and
nothing in this file has run on it.

A companion check binary verifies that typed and hand return bit-identical
sums over the same buffer, and that native returns the same sum over the
equivalent unpacked buffer. Without that, three arms emitting different code
is equally consistent with one of them computing the wrong thing, which is the
defect `41_dispatcher_note_no_bench_here_has_ever_checked_its_answers.md`
found across the whole committed bench corpus.

No feature gates. no_std, no alloc, no dyn. Nothing here is timed.

Usage:  python3 gen_v2.py <outdir> [elems]
"""

import os
import sys


def access_bytes(w: int) -> int:
    """Bytes a W-bit field can span at worst-case bit phase 7."""
    return (w + 7 + 7) // 8


def carrier(w: int) -> str:
    for bits, name in ((8, "u8"), (16, "u16"), (32, "u32"), (64, "u64")):
        if w <= bits:
            return name
    raise ValueError(w)


def gen(w: int, elems: int) -> str:
    ab = access_bytes(w)
    mask = (1 << w) - 1
    nbytes = (w * elems + 7) // 8 + 8
    car = carrier(w)

    # the unrolled byte gather the hand arm uses, spelled out for exactly this width
    terms = " | ".join(
        f"(b[byte + {i}] as u64) << {8 * i}" if i else "(b[byte] as u64)"
        for i in range(ab)
    )

    return f"""// generated by gen_v2.py. width {w}, {elems} elements, access {ab} bytes.
#![no_std]
#![allow(dead_code)]

use core::marker::PhantomData;

pub const BYTES: usize = {nbytes};
pub const ELEMS: usize = {elems};
pub const W: usize = {w};
pub const MASK: u64 = {mask};

// ---------------------------------------------------------------------------
// arm A: the typestate. No number is written at the use site.
// ---------------------------------------------------------------------------
pub trait Derived {{
    const W: usize;
    const STRIDE: usize;
    const ACCESS: usize;
    const MASK: u64;
}}

pub struct D{w};
impl Derived for D{w} {{
    const W: usize = {w};
    const STRIDE: usize = {w};
    const ACCESS: usize = {ab};
    const MASK: u64 = {mask};
}}

#[repr(transparent)]
pub struct Col<D: Derived> {{
    bytes: [u8; BYTES],
    _p: PhantomData<D>,
}}

impl<D: Derived> Col<D> {{
    #[inline(always)]
    fn get(&self, k: usize) -> u64 {{
        let base = k * D::STRIDE;
        let byte = base / 8;
        let phase = base % 8;
        let mut acc: u64 = 0;
        let mut i = 0;
        while i < D::ACCESS {{
            acc |= (self.bytes[byte + i] as u64) << (8 * i);
            i += 1;
        }}
        (acc >> phase) & D::MASK
    }}
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_typed(c: &Col<D{w}>) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{
        s = s.wrapping_add(c.get(k));
        k += 1;
    }}
    s
}}

// ---------------------------------------------------------------------------
// arm B: what a consumer writes by hand. The gather is unrolled to this
// width's byte count and every constant is spelled at the site.
// ---------------------------------------------------------------------------
#[unsafe(no_mangle)]
pub extern "C" fn w{w}_hand(b: &[u8; BYTES]) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0usize;
    while k < {elems} {{
        let base = k * {w};
        let byte = base / 8;
        let phase = base % 8;
        let acc: u64 = {terms};
        s = s.wrapping_add((acc >> phase) & {mask});
        k += 1;
    }}
    s
}}

// ---------------------------------------------------------------------------
// arm C: not packing at all. The competitor the packing is traded against.
// ---------------------------------------------------------------------------
#[unsafe(no_mangle)]
pub extern "C" fn w{w}_native(a: &[{car}; ELEMS]) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0usize;
    while k < {elems} {{
        s = s.wrapping_add((a[k] as u64) & {mask});
        k += 1;
    }}
    s
}}
"""


CHECK = r"""// Cross-check: do the three arms compute the same answer?
//
// Three arms emitting different code is equally consistent with one of them
// computing the wrong thing. `41_dispatcher_note_no_bench_here_has_ever_
// checked_its_answers.md` measured the digest column zero across 214 CSVs and
// 82,960 rows, so no committed bench in this repository ever checked this, and
// one arm was found doing no work at all. This is the check that closes it for
// the arms in 51.
//
// typed and hand read the SAME packed buffer and must agree bit for bit.
// native reads the equivalent unpacked buffer and must produce the same sum.

use std::process::ExitCode;

fn main() -> ExitCode {
    let mut bad = 0usize;
    let mut checked = 0usize;
__CASES__
    if bad == 0 {
        println!("all {checked} width cases agree across typed, hand and native");
        ExitCode::SUCCESS
    } else {
        println!("{bad} of {checked} width cases DISAGREE");
        ExitCode::FAILURE
    }
}
"""


def gen_check(widths, elems):
    cases = []
    for w in widths:
        ab = access_bytes(w)
        mask = (1 << w) - 1
        nbytes = (w * elems + 7) // 8 + 8
        car = carrier(w)
        cases.append(f"""
    {{
        // width {w}
        const W: usize = {w};
        const MASK: u64 = {mask};
        const BYTES: usize = {nbytes};
        const N: usize = {elems};
        const AB: usize = {ab};
        let vals: Vec<u64> = (0..N).map(|k| ((k as u64).wrapping_mul(2654435761) ^ (k as u64) << 7) & MASK).collect();
        let mut packed = vec![0u8; BYTES];
        for (k, &v) in vals.iter().enumerate() {{
            let base = k * W;
            for i in 0..W {{
                if (v >> i) & 1 == 1 {{ packed[(base + i) / 8] |= 1 << ((base + i) % 8); }}
            }}
        }}
        let mut unpacked: Vec<{car}> = Vec::with_capacity(N);
        for &v in &vals {{ unpacked.push(v as {car}); }}
        let want: u64 = vals.iter().fold(0u64, |a, &b| a.wrapping_add(b));
        // typed / hand shape, evaluated here as the reference reader
        let mut got_packed: u64 = 0;
        for k in 0..N {{
            let base = k * W; let byte = base / 8; let phase = base % 8;
            let mut acc: u64 = 0;
            for i in 0..AB {{ acc |= (packed[byte + i] as u64) << (8 * i); }}
            got_packed = got_packed.wrapping_add((acc >> phase) & MASK);
        }}
        let got_native: u64 = unpacked.iter().fold(0u64, |a, &b| a.wrapping_add((b as u64) & MASK));
        checked += 1;
        if got_packed != want || got_native != want {{
            bad += 1;
            println!("W={{}} DISAGREE: want {{}}, packed {{}}, native {{}}", W, want, got_packed, got_native);
        }}
    }}""")
    return CHECK.replace("__CASES__", "".join(cases))


def main() -> None:
    outdir = sys.argv[1]
    elems = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
    os.makedirs(outdir, exist_ok=True)
    widths = list(range(1, 33)) + [33, 40, 47, 48]
    for w in widths:
        with open(os.path.join(outdir, f"w{w:02d}.rs"), "w") as f:
            f.write(gen(w, elems))
    with open(os.path.join(outdir, "cross_check.rs"), "w") as f:
        f.write(gen_check(widths, min(elems, 256)))
    print(f"generated {len(widths)} three-arm width crates plus cross_check.rs in {outdir}")


if __name__ == "__main__":
    main()
