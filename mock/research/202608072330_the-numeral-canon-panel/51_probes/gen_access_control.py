#!/usr/bin/env python3
"""Control: hold the width fixed and sweep only the access-byte count.

In the width matrix two things move together at the boundary. The declared
width crosses 17 to 18, and the access window crosses 3 bytes to 4. Either
could be what the unroller is responding to, and the matrix cannot tell them
apart because they are the same event in it.

This fixes W at 13 and varies ACCESS from 1 to 8. Reading extra high bytes is
harmless because the result is masked to W bits, so every arm still computes
the same answer at every ACCESS, which the emitted-symbol cross-check confirms.
If the collapse tracks ACCESS rather than W, it appears here at the same place.

  python3 gen_access_control.py <outdir>
"""

import os
import sys

W = 13
ELEMS = 1000
MASK = (1 << W) - 1
BYTES = (W * ELEMS + 7) // 8 + 8


def flat(ab, arr, idx):
    return " | ".join(
        f"(({arr}[{idx} + {i}] as u64) << {8 * i})" if i else f"{arr}[{idx}] as u64"
        for i in range(ab)
    )


def gen(ab: int) -> str:
    return f"""// generated by gen_access_control.py. width {W} fixed, access {ab} bytes.
#![no_std]
#![allow(dead_code)]

#[cfg(link_check)]
#[panic_handler]
fn ph(_: &core::panic::PanicInfo) -> ! {{ loop {{}} }}

pub const BYTES: usize = {BYTES};
pub const ELEMS: usize = {ELEMS};
const ACCESS: usize = {ab};

#[repr(transparent)]
pub struct Col {{ bytes: [u8; BYTES] }}

/// the loop form: the access count is a bound on a loop
#[unsafe(no_mangle)]
pub extern "C" fn a{ab}_loop(c: &Col) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{
        let base = k * {W};
        let byte = base / 8;
        let mut acc: u64 = 0;
        let mut i = 0;
        while i < ACCESS {{
            acc |= (c.bytes[byte + i] as u64) << (8 * i);
            i += 1;
        }}
        s = s.wrapping_add((acc >> (base % 8)) & {MASK});
        k += 1;
    }}
    s
}}

/// the flat form: the same access count, spelled out
#[unsafe(no_mangle)]
pub extern "C" fn a{ab}_flat(c: &Col) -> u64 {{
    let b = &c.bytes;
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{
        let base = k * {W};
        let byte = base / 8;
        let acc: u64 = {flat(ab, 'b', 'byte')};
        s = s.wrapping_add((acc >> (base % 8)) & {MASK});
        k += 1;
    }}
    s
}}
"""


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    for ab in range(1, 9):
        with open(os.path.join(outdir, f"a{ab}.rs"), "w") as f:
            f.write(gen(ab))
    print(f"generated 8 access-count crates at fixed width {W} in {outdir}")


if __name__ == "__main__":
    main()
