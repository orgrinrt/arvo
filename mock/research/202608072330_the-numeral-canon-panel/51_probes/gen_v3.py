#!/usr/bin/env python3
"""Five arms per width. Adds two attacks on the mechanism v2 found.

v2 established that a typestate packed walk stops matching its hand-written
twin at W >= 18, which is exactly where the access window goes from 3 bytes to
4. The typed arm collapses from four elements per iteration with five
independent accumulators to one element per iteration with one accumulator, so
the loop-carried chain per element goes from about 2 dependent instructions to
6. The instruction count is not the problem; the reduction serialising is.

The suspected mechanism is the generic gather. The typestate writes the byte
gather as `while i < D::ACCESS`, which is a nested loop that has to be
simplified away before the outer reduction can be unrolled. The hand arm has
the gather already flat in source, so the outer loop is a simple loop when the
unroller looks at it.

If that is the mechanism then the fix is not to write numbers at the use site.
It is to move the gather out of a loop bound and into a contract with one impl
per access width, which is the shape `a-refused-bound-wants-a-trait-not-a-
feature.md` prescribes for a constraint that will not go into one place:
decompose it into named pieces that each hold on their own.

  wN_typed      v2's arm A unchanged. Gather is `while i < D::ACCESS`.
  wN_hand       v2's arm B unchanged. Gather flat in source with literals.
  wN_native     v2's arm C unchanged. No packing at all.
  wN_gather     ATTACK 1. Coordinates still all arrive from the typestate and
                no number is written at the use site, but the gather arrives
                as an associated type whose impl is flat for that access
                width. Nothing about what the consumer writes changes.
  wN_wide       ATTACK 2. The typestate knows the buffer carries slack, so the
                gather becomes one fixed 8-byte load and a shift, with no
                per-width gather at all. This is the "supply the wider load"
                move and it costs the buffer 8 bytes of tail.

Arms 4 and 5 are still typestate arms: the consumer writes the same thing in
all three. What differs is what the derivation hands the backend.

No feature gates. no_std, no alloc. Nothing here is timed.

  python3 gen_v3.py <outdir> [elems]
"""

import os
import sys


def access_bytes(w: int) -> int:
    return (w + 7 + 7) // 8


def carrier(w: int) -> str:
    for bits, name in ((8, "u8"), (16, "u16"), (32, "u32"), (64, "u64")):
        if w <= bits:
            return name
    raise ValueError(w)


def flat_gather(ab: int, arr: str, idx: str) -> str:
    return " | ".join(
        f"(({arr}[{idx} + {i}] as u64) << {8 * i})" if i else f"{arr}[{idx}] as u64"
        for i in range(ab)
    )


def gen(w: int, elems: int) -> str:
    ab = access_bytes(w)
    mask = (1 << w) - 1
    nbytes = (w * elems + 7) // 8 + 8
    car = carrier(w)

    gatherers = "\n".join(
        f"""pub struct G{n};
impl Gather for G{n} {{
    const BYTES: usize = {n};
    #[inline(always)]
    fn gather(b: &[u8; BYTES], byte: usize) -> u64 {{
        {flat_gather(n, 'b', 'byte')}
    }}
}}"""
        for n in range(1, 9)
    )

    return f"""// generated by gen_v3.py. width {w}, {elems} elements, access {ab} bytes.
#![no_std]
#![allow(dead_code)]

use core::marker::PhantomData;

// Only for the link-and-call cross-check, which needs a no_std staticlib.
// Every measured build passes the same --cfg, so the artifact that is checked
// and the artifact that is read are the same build.
#[cfg(link_check)]
#[panic_handler]
fn ph(_: &core::panic::PanicInfo) -> ! {{ loop {{}} }}

pub const BYTES: usize = {nbytes};
pub const ELEMS: usize = {elems};

pub trait Gather {{
    const BYTES: usize;
    fn gather(b: &[u8; BYTES], byte: usize) -> u64;
}}

{gatherers}

pub trait Derived {{
    const W: usize;
    const STRIDE: usize;
    const ACCESS: usize;
    const MASK: u64;
    type G: Gather;
}}

pub struct D{w};
impl Derived for D{w} {{
    const W: usize = {w};
    const STRIDE: usize = {w};
    const ACCESS: usize = {ab};
    const MASK: u64 = {mask};
    type G = G{ab};
}}

#[repr(transparent)]
pub struct Col<D: Derived> {{
    bytes: [u8; BYTES],
    _p: PhantomData<D>,
}}

impl<D: Derived> Col<D> {{
    /// arm A: the gather is a loop over an associated const.
    #[inline(always)]
    fn get_loop(&self, k: usize) -> u64 {{
        let base = k * D::STRIDE;
        let byte = base / 8;
        let phase = base % 8;
        let mut acc: u64 = 0;
        let mut i = 0;
        while i < D::ACCESS {{
            acc |= (self.bytes[byte + i] as u64) << (8 * i);
            i += 1;
        }}
        (acc >> phase) & D::MASK
    }}

    /// arm D: the gather is an associated type whose impl is flat.
    #[inline(always)]
    fn get_gather(&self, k: usize) -> u64 {{
        let base = k * D::STRIDE;
        (D::G::gather(&self.bytes, base / 8) >> (base % 8)) & D::MASK
    }}

    /// arm E: one fixed-width load into the buffer's slack tail.
    #[inline(always)]
    fn get_wide(&self, k: usize) -> u64 {{
        let base = k * D::STRIDE;
        let byte = base / 8;
        let mut w = [0u8; 8];
        let mut i = 0;
        while i < 8 {{
            w[i] = self.bytes[byte + i];
            i += 1;
        }}
        (u64::from_le_bytes(w) >> (base % 8)) & D::MASK
    }}
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_typed(c: &Col<D{w}>) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{ s = s.wrapping_add(c.get_loop(k)); k += 1; }}
    s
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_gather(c: &Col<D{w}>) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{ s = s.wrapping_add(c.get_gather(k)); k += 1; }}
    s
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_wide(c: &Col<D{w}>) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{ s = s.wrapping_add(c.get_wide(k)); k += 1; }}
    s
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_hand(b: &[u8; BYTES]) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0usize;
    while k < {elems} {{
        let base = k * {w};
        let byte = base / 8;
        let phase = base % 8;
        let acc: u64 = {flat_gather(ab, 'b', 'byte')};
        s = s.wrapping_add((acc >> phase) & {mask});
        k += 1;
    }}
    s
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_native(a: &[{car}; ELEMS]) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0usize;
    while k < {elems} {{ s = s.wrapping_add((a[k] as u64) & {mask}); k += 1; }}
    s
}}
"""


def main() -> None:
    outdir = sys.argv[1]
    elems = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
    os.makedirs(outdir, exist_ok=True)
    widths = list(range(1, 33)) + [33, 40, 47, 48]
    for w in widths:
        with open(os.path.join(outdir, f"w{w:02d}.rs"), "w") as f:
            f.write(gen(w, elems))
    print(f"generated {len(widths)} five-arm width crates in {outdir}")


if __name__ == "__main__":
    main()
