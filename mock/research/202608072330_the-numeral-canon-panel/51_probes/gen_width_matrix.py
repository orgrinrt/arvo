#!/usr/bin/env python3
"""Generate one typed-vs-handwritten packed-walk pair per declared width.

The erasure evidence under this topic is quantified over a single width (13),
in `17_probes/t2_aggregate_erasure.rs`. A law asserted at one instantiation of
an axis the design is parameterised over is a sampled law: whoever picked the
sample picked what not to find out. This generates the whole matrix so the
failures land wherever they land.

Per width W it emits a crate with two `#[no_mangle] extern "C"` walks over the
same packed byte array:

  wN_typed        every layout coordinate arrives through an associated const
                  on a trait impl, which is the typestate side.
  wN_hand         the same coordinates written as literals at the use site,
                  which is what "exactly what you describe" means in the
                  acceptance criterion.

Both walk the same element count over the same buffer with the same algorithm.
Any instruction the typed side emits and the hand side does not is the
typestate failing to erase.

No feature gates, no_std, no alloc. Nothing here is timed and nothing here is a
bench: it emits assembly and counts what is in it. Counts are counts.

Usage:  python3 gen_width_matrix.py <outdir>
"""

import os
import sys


def access_bytes(w: int) -> int:
    """Bytes a W-bit field can span at worst-case bit phase 7."""
    return (w + 7 + 7) // 8


def gen(w: int, elems: int) -> str:
    total_bits = w * elems
    nbytes = (total_bits + 7) // 8 + 8  # slack so no walk reads out of range
    ab = access_bytes(w)
    mask = (1 << w) - 1
    return f"""// generated by gen_width_matrix.py. width {w}, {elems} elements.
// access window {ab} bytes, stride {w} bits, buffer {nbytes} bytes.
#![no_std]
#![allow(dead_code)]

use core::marker::PhantomData;

pub const BYTES: usize = {nbytes};
pub const ELEMS: usize = {elems};

/// The derivation. Every layout coordinate is an associated const, so the use
/// site never writes a number: it asks the type.
pub trait Derived {{
    const W: usize;
    const STRIDE: usize;
    const ACCESS: usize;
    const MASK: u64;
}}

pub struct D{w};
impl Derived for D{w} {{
    const W: usize = {w};
    const STRIDE: usize = {w};
    const ACCESS: usize = {ab};
    const MASK: u64 = {mask};
}}

#[repr(transparent)]
pub struct Col<D: Derived> {{
    bytes: [u8; BYTES],
    _p: PhantomData<D>,
}}

impl<D: Derived> Col<D> {{
    #[inline(always)]
    fn get(&self, k: usize) -> u64 {{
        let base = k * D::STRIDE;
        let byte = base / 8;
        let phase = base % 8;
        let mut acc: u64 = 0;
        let mut i = 0;
        while i < D::ACCESS {{
            acc |= (self.bytes[byte + i] as u64) << (8 * i);
            i += 1;
        }}
        (acc >> phase) & D::MASK
    }}
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_typed(c: &Col<D{w}>) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0;
    while k < ELEMS {{
        s = s.wrapping_add(c.get(k));
        k += 1;
    }}
    s
}}

#[unsafe(no_mangle)]
pub extern "C" fn w{w}_hand(b: &[u8; BYTES]) -> u64 {{
    let mut s: u64 = 0;
    let mut k = 0usize;
    while k < ELEMS {{
        let base = k * {w};
        let byte = base / 8;
        let phase = base % 8;
        let mut acc: u64 = 0;
        let mut i = 0;
        while i < {ab} {{
            acc |= (b[byte + i] as u64) << (8 * i);
            i += 1;
        }}
        s = s.wrapping_add((acc >> phase) & {mask});
        k += 1;
    }}
    s
}}
"""


def main() -> None:
    outdir = sys.argv[1]
    elems = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
    os.makedirs(outdir, exist_ok=True)
    widths = list(range(1, 33)) + [33, 40, 47, 48]
    for w in widths:
        with open(os.path.join(outdir, f"w{w:02d}.rs"), "w") as f:
            f.write(gen(w, elems))
    print(f"generated {len(widths)} width crates in {outdir} at {elems} elements")


if __name__ == "__main__":
    main()
