#!/usr/bin/env python3
"""Regenerate this spike's `src/lib.rs` for one of its four sweeps.

The spike exports one monomorphisation per arm per configuration so a hot loop
can be disassembled in isolation. The bench's own arm functions inline thirty
monomorphisations each, so counting instructions in one of them mixes every
width together.

`src/lib.rs` was regenerated for each sweep rather than carrying all four at
once, so the committed copy is whichever sweep ran last. This script is how any
of them is reproduced, which is what makes the four output files in this
directory checkable rather than merely present.

    python3 gen.py width   > src/lib.rs   # -> raw_output.txt (first block)
    python3 gen.py density > src/lib.rs   # -> raw_output.txt (D sweep)
    python3 gen.py tail    > src/lib.rs   # -> tail_sweep_output.txt
    python3 gen.py walk    > src/lib.rs   # -> walk_loop_output.txt, contiguity_output.txt

Then `cargo build --release` and disassemble with `objdump -d`.

Not a bench. No timer anywhere in the emitted crate.
"""

import sys

HEAD = '''//! One monomorphisation per arm per configuration, exported so each loop can be
//! disassembled in isolation.
//!
//! Generated by `gen.py`. See that file for which sweep produced which output.
//!
//! Not a bench. It has no timer, and by this workspace's own standard a
//! measurement outside `mock/benches/` on the harness is an ad-hoc quick spike
//! with no substance. An instruction count is a structural fact, which is the
//! one kind of claim a spike can carry.

use bench_wide_rung_shared::load::__IMPORTS__;
use bench_wide_rung_shared::run;
'''

ARMS = [
    ("ragged", "Ragged"),
    ("ragged_overread", "RaggedOverread"),
    ("wordround", "WordRound"),
    ("align16", "Align16"),
]

# The six widths the harness sweeps, all above the 128-bit native rung.
SWEPT = [129, 160, 192, 200, 232, 256]
# Every ragged tail residue, limb count held at four so only the tail moves.
TAILS = [192, 200, 208, 216, 224, 232, 240, 248, 256]


def emit(prefix, w, d, fname, ty):
    return f'''
/// # Safety
/// `base` must satisfy the loader's contract for `n` elements at `W = {w}`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn {prefix}(base: *const u8, n: usize, out: *mut u64) {{
    let v = run::<{ty}, {w}, {d}>(base, n);
    unsafe {{ core::ptr::write(out as *mut [u64; 4], v) }};
}}'''


def build(sweep):
    body = []
    if sweep == "width":
        for w in SWEPT:
            for fname, ty in ARMS:
                body.append(emit(f"loop_{fname}_w{w}", w, 3, fname, ty))
    elif sweep == "density":
        for w in SWEPT:
            for fname, ty in ARMS:
                for d in (1, 3, 8):
                    body.append(emit(f"loop_{fname}_w{w}_d{d}", w, d, fname, ty))
    elif sweep == "tail":
        for w in TAILS:
            for fname, ty in ARMS[:3]:
                body.append(emit(f"tail_{fname}_w{w}", w, 3, fname, ty))
    elif sweep == "walk":
        for w in SWEPT:
            for fname, ty in (ARMS[0], ARMS[2]):
                body.append(emit(f"walk_{fname}_w{w}", w, 0, fname, ty))
    else:
        raise SystemExit(f"unknown sweep {sweep!r}; one of width, density, tail, walk")
    used = sorted({ty for _, ty in (ARMS if sweep in ("width", "density")
                                    else ARMS[:3] if sweep == "tail"
                                    else (ARMS[0], ARMS[2]))})
    return HEAD.replace("__IMPORTS__", "{" + ", ".join(used) + "}") + "\n".join(body) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    sys.stdout.write(build(sys.argv[1]))
