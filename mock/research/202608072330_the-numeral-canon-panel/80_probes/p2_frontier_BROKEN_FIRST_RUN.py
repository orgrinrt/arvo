#!/usr/bin/env python3
"""p2: where the compile-time validation of a law stops being possible, as a
function of the law's ARITY as well as the numeral's width.

`68_probes/p5_const_eval_ceiling.rs` established the wall for one law at one arity
(signed saturating associativity, arity 3) and reported it as a width: refused at
w = 9. The workspace droplist separately records that the wall is a total-step-count
budget rather than a width ceiling. Neither states the consequence, which is that the
wall is a curve in (width, arity) and the arity axis is the one a chain law moves
along.

Method. For each arity k, emit a file whose top-level `const` exhaustively enumerates
every k-tuple over the signed window of width W and checks that the left fold and the
right fold of the policy's addition agree. Compile it on the pinned nightly. Record
whether rustc accepts, refuses under `long_running_const_eval`, or fails otherwise.
Walk W upward per k until the first refusal.

The accept/refuse outcome is a compile fact and is what this probe establishes.
The wall-clock figures printed alongside are an ad-hoc quick spike with no substance
and are not a benchmark; they are recorded only so a later reader can see the shape
of the approach to the wall rather than being asked to trust the boundary alone.
"""

import subprocess, sys, time, os, json

TOOLCHAIN = "nightly-2026-05-28"
TIMEOUT = 180

TEMPLATE = r'''
// generated by p2_frontier.py : width={W} arity={K}
const W: i32 = {W};
const LO: i32 = -(1 << (W - 1));
const HI: i32 = (1 << (W - 1)) - 1;
const K: usize = {K};

const fn sat_add(a: i32, b: i32) -> i32 {{
    let s = a + b;
    if s > HI {{ HI }} else if s < LO {{ LO }} else {{ s }}
}}

const fn left_fold(xs: &[i32; K]) -> i32 {{
    let mut acc = xs[0];
    let mut i = 1;
    while i < K {{ acc = sat_add(acc, xs[i]); i += 1; }}
    acc
}}

const fn right_fold(xs: &[i32; K]) -> i32 {{
    let mut acc = xs[K - 1];
    let mut i = K - 1;
    while i > 0 {{ i -= 1; acc = sat_add(xs[i], acc); }}
    acc
}}

/// Exhaustive over every k-tuple of the window: (2^W)^K tuples.
const fn law_holds() -> bool {{
    let mut idx: u64 = 0;
    let span: u64 = (HI - LO + 1) as u64;
    let total: u64 = {TOTAL};
    while idx < total {{
        let mut xs = [0i32; K];
        let mut rem = idx;
        let mut j = 0;
        while j < K {{
            xs[j] = (rem % span) as i32 + LO;
            rem /= span;
            j += 1;
        }}
        if left_fold(&xs) != right_fold(&xs) {{ return false; }}
        idx += 1;
    }}
    true
}}

const VERDICT: bool = law_holds();

fn main() {{ println!("width={{}} arity={{}} verdict={{}}", W, K, VERDICT); }}
'''


def run(w, k, outdir):
    total = (2 ** w) ** k
    src = TEMPLATE.format(W=w, K=k, TOTAL=total)
    path = os.path.join(outdir, f"gen_w{w}_k{k}.rs")
    with open(path, "w") as f:
        f.write(src)
    t0 = time.time()
    try:
        p = subprocess.run(
            ["rustc", f"+{TOOLCHAIN}", "--edition", "2021", "-O", path,
             "-o", os.path.join(outdir, f"gen_w{w}_k{k}")],
            capture_output=True, text=True, timeout=TIMEOUT,
        )
        dt = time.time() - t0
        err = p.stderr
        if p.returncode == 0:
            return ("accept", dt, "")
        if "long_running_const_eval" in err or "const_eval_long_running" in err:
            return ("refuse-long-running", dt, err.strip().splitlines()[0] if err.strip() else "")
        return ("error", dt, err.strip()[:400])
    except subprocess.TimeoutExpired:
        return ("timeout", time.time() - t0, "")


def main():
    outdir = os.path.dirname(os.path.abspath(__file__))
    gen = os.path.join(outdir, "p2_generated")
    os.makedirs(gen, exist_ok=True)
    rows = []
    for k in (2, 3, 4, 5, 6, 8):
        w = 1
        while w <= 16:
            status, dt, note = run(w, k, gen)
            total = (2 ** w) ** k
            rows.append(dict(arity=k, width=w, tuples=total,
                             log2_tuples=w * k, status=status,
                             seconds=round(dt, 2), note=note))
            print(f"arity={k:2d} width={w:2d}  tuples=2^{w*k:<3d}  "
                  f"{status:<20s} {dt:7.2f}s  {note[:70]}")
            sys.stdout.flush()
            if status != "accept":
                break
            w += 1
    with open(os.path.join(outdir, "p2_frontier.json"), "w") as f:
        json.dump(rows, f, indent=1)
    print()
    print("first non-accepting width per arity, and the tuple count there:")
    for k in sorted({r["arity"] for r in rows}):
        bad = [r for r in rows if r["arity"] == k and r["status"] != "accept"]
        good = [r for r in rows if r["arity"] == k and r["status"] == "accept"]
        if bad:
            b = bad[0]
            print(f"  arity {k}: widest accepted W={max(g['width'] for g in good) if good else '-'}, "
                  f"first refused W={b['width']} at 2^{b['log2_tuples']} tuples ({b['status']})")
        else:
            print(f"  arity {k}: no refusal up to W={max(g['width'] for g in good)}")


if __name__ == "__main__":
    main()
