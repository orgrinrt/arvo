#!/usr/bin/env python3
"""p2: where the compile-time validation of a law stops being possible, as a
function of the law's ARITY as well as the numeral's width.

`68_probes/p5_const_eval_ceiling.rs` established the wall for one law at one arity
(signed saturating associativity, arity 3) and reported it as a width: refused at
w = 9. The workspace droplist separately records that the wall is a total-step-count
budget rather than a width ceiling. Neither states the consequence, which is that
the wall is a curve in (width, arity) and the arity axis is the one a chain law
moves along.

Method. For each arity K, emit a file whose top-level `const` enumerates every
K-tuple over the signed window of width W, in a nest of K loops, and COUNTS the
tuples on which the left fold and the right fold of the policy's addition disagree.
Counting rather than returning early is load-bearing: an early return makes the
evaluator stop at the first counterexample, so the domain the probe claims to
enumerate is never enumerated. See NOTE_p2_first_run.md for the run that did that.

Compile on the pinned nightly. Record accept, refusal under
`long_running_const_eval`, or another failure. Walk W upward per K until the first
non-accepting result.

The accept/refuse outcome is a compile fact and is what this probe establishes. The
wall-clock figures printed alongside are an ad-hoc quick spike with no substance and
are not a benchmark; they are recorded so a reader can see the approach to the wall
rather than being asked to trust the boundary alone.
"""

import subprocess, sys, time, os, json

TOOLCHAIN = "nightly-2026-05-28"
TIMEOUT = 300

HEADER = r'''
// generated by p2_frontier.py : width={W} arity={K}
// exhaustive, counting, no early return.
const W: i32 = {W};
const LO: i32 = -(1 << (W - 1));
const HI: i32 = (1 << (W - 1)) - 1;
const K: usize = {K};

const fn sat_add(a: i32, b: i32) -> i32 {{
    let s = a + b;
    if s > HI {{ HI }} else if s < LO {{ LO }} else {{ s }}
}}

const fn left_fold(xs: &[i32; K]) -> i32 {{
    let mut acc = xs[0];
    let mut i = 1;
    while i < K {{ acc = sat_add(acc, xs[i]); i += 1; }}
    acc
}}

const fn right_fold(xs: &[i32; K]) -> i32 {{
    let mut acc = xs[K - 1];
    let mut i = K - 1;
    while i > 0 {{ i -= 1; acc = sat_add(xs[i], acc); }}
    acc
}}

/// Exhaustive over every K-tuple of the window. Counts violations; never returns
/// early, so the whole domain is visited whatever the verdict turns out to be.
const fn violations() -> u64 {{
    let mut bad: u64 = 0;
{LOOPS_OPEN}
{BODY}
{LOOPS_CLOSE}
    bad
}}

const COUNT: u64 = violations();

fn main() {{ println!("width={{}} arity={{}} violations={{}}", W, K, COUNT); }}
'''


def gen(w, k):
    opens, closes = [], []
    for j in range(k):
        ind = "    " * (j + 1)
        opens.append(f"{ind}let mut v{j} = LO;\n{ind}while v{j} <= HI {{")
        closes.append("    " * (k - j) + f"v{k - 1 - j} += 1;\n" + "    " * (k - j) + "}")
    ind = "    " * (k + 1)
    args = ", ".join(f"v{j}" for j in range(k))
    body = (f"{ind}let xs = [{args}];\n"
            f"{ind}if left_fold(&xs) != right_fold(&xs) {{ bad += 1; }}")
    return HEADER.format(W=w, K=k,
                         LOOPS_OPEN="\n".join(opens),
                         BODY=body,
                         LOOPS_CLOSE="\n".join(closes))


def run(w, k, outdir):
    path = os.path.join(outdir, f"gen_w{w}_k{k}.rs")
    with open(path, "w") as f:
        f.write(gen(w, k))
    t0 = time.time()
    try:
        p = subprocess.run(
            ["rustc", f"+{TOOLCHAIN}", "--edition", "2021", "-O", path,
             "-o", os.path.join(outdir, f"gen_w{w}_k{k}")],
            capture_output=True, text=True, timeout=TIMEOUT,
        )
        dt = time.time() - t0
        err = p.stderr
        if p.returncode == 0:
            return ("accept", dt, "")
        if "taking a long time" in err or "long_running_const_eval" in err:
            return ("refuse-long-running", dt, "")
        return ("error", dt, " ".join(err.strip().split())[:200])
    except subprocess.TimeoutExpired:
        return ("timeout", time.time() - t0, "")


def main():
    outdir = os.path.dirname(os.path.abspath(__file__))
    gendir = os.path.join(outdir, "p2_generated")
    os.makedirs(gendir, exist_ok=True)
    rows = []
    for k in (1, 2, 3, 4, 5, 6, 8, 12):
        w = 1
        while w <= 30:
            status, dt, note = run(w, k, gendir)
            rows.append(dict(arity=k, width=w, log2_tuples=w * k,
                             status=status, seconds=round(dt, 2), note=note))
            print(f"arity={k:2d} width={w:2d}  tuples=2^{w*k:<3d}  "
                  f"{status:<20s} {dt:7.2f}s  {note[:70]}")
            sys.stdout.flush()
            if status != "accept":
                break
            w += 1
    with open(os.path.join(outdir, "p2_frontier.json"), "w") as f:
        json.dump(rows, f, indent=1)

    print()
    print("frontier: widest width whose exhaustive law check rustc will evaluate,")
    print("and the log2 of the tuple count at that point.")
    print()
    print(f"{'arity':>6} {'widest accepted W':>18} {'log2 tuples there':>18} "
          f"{'first refused W':>16} {'log2 tuples there':>18}")
    for k in sorted({r["arity"] for r in rows}):
        good = [r for r in rows if r["arity"] == k and r["status"] == "accept"]
        bad = [r for r in rows if r["arity"] == k and r["status"] != "accept"]
        gw = max((g["width"] for g in good), default=None)
        gl = gw * k if gw else None
        bw = bad[0]["width"] if bad else None
        bl = bw * k if bw else None
        print(f"{k:>6} {str(gw):>18} {str(gl):>18} {str(bw):>16} {str(bl):>18}"
              + ("" if not bad else f"   ({bad[0]['status']})"))


if __name__ == "__main__":
    main()
