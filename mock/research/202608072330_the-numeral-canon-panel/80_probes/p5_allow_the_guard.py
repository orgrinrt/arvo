#!/usr/bin/env python3
"""p5: attacking p2's frontier. The guard is a deny-by-default lint, so it can be
allowed. How far does allowing it actually move the frontier?

`68:207-209` notes the lint is allowable and calls the cost "unpriced and rapidly
growing". This walks it: the same exhaustive arity-3 associativity check as p2, with
`#![allow(long_running_const_eval)]`, at widths 6 upward, with a wall-clock cap.

The accept/refuse/timeout outcome is a compile fact. The seconds are an ad-hoc quick
spike with no substance and are not a benchmark; they are recorded so a reader can
see the growth rate rather than being asked to trust the boundary alone.

Both policies are run, because p2b established that a false verdict exits early and
a true one does not, so the true one (wrap) is the honest measurement of the cost.
"""

import subprocess, time, os, sys, json

TOOLCHAIN = "nightly-2026-05-28"
CAP = 900

SRC = r'''#![allow(long_running_const_eval)]
// generated by p5_allow_the_guard.py : width={W} policy={P}
const W: i32 = {W};
const LO: i32 = -(1i32 << (W - 1));
const HI: i32 = (1i32 << (W - 1)) - 1;
const N: i64 = (HI as i64) - (LO as i64) + 1;

const fn op(a: i64, b: i64) -> i64 {{
    if {WRAP} {{
        let mut r = (a + b - LO as i64) % N;
        if r < 0 {{ r += N; }}
        r + LO as i64
    }} else {{
        let s = a + b;
        if s > HI as i64 {{ HI as i64 }} else if s < LO as i64 {{ LO as i64 }} else {{ s }}
    }}
}}

const fn violations() -> u64 {{
    let mut bad: u64 = 0;
    let mut a = LO as i64;
    while a <= HI as i64 {{
        let mut b = LO as i64;
        while b <= HI as i64 {{
            let mut c = LO as i64;
            while c <= HI as i64 {{
                if op(op(a, b), c) != op(a, op(b, c)) {{ bad += 1; }}
                c += 1;
            }}
            b += 1;
        }}
        a += 1;
    }}
    bad
}}

const COUNT: u64 = violations();
fn main() {{ println!("W={{}} policy={P} violations={{}}", W, COUNT); }}
'''


def run(w, policy, outdir):
    src = SRC.format(W=w, P=policy, WRAP=("true" if policy == "wrap" else "false"))
    path = os.path.join(outdir, f"allow_w{w}_{policy}.rs")
    with open(path, "w") as f:
        f.write(src)
    t0 = time.time()
    try:
        p = subprocess.run(
            ["rustc", f"+{TOOLCHAIN}", "--edition", "2021", "-O", path,
             "-o", os.path.join(outdir, f"allow_w{w}_{policy}")],
            capture_output=True, text=True, timeout=CAP)
        dt = time.time() - t0
        if p.returncode == 0:
            return ("accept", dt)
        head = " ".join(p.stderr.strip().split())[:160]
        return (f"error: {head}", dt)
    except subprocess.TimeoutExpired:
        return (f"timeout>{CAP}s", time.time() - t0)


def main():
    outdir = os.path.dirname(os.path.abspath(__file__))
    gen = os.path.join(outdir, "p5_generated")
    os.makedirs(gen, exist_ok=True)
    rows = []
    print("p5: the frontier with the guard allowed. arity 3, exhaustive, counting.")
    print("seconds are an ad-hoc quick spike, not a bench.")
    print()
    for policy in ("wrap", "sat"):
        for w in range(6, 13):
            status, dt = run(w, policy, gen)
            rows.append(dict(policy=policy, width=w, tuples=f"2^{3*w}",
                             status=status, seconds=round(dt, 2)))
            print(f"policy={policy:<5s} width={w:2d}  triples=2^{3*w:<3d}  "
                  f"{status:<30s} {dt:8.2f}s")
            sys.stdout.flush()
            if status.startswith("timeout"):
                break
    with open(os.path.join(outdir, "p5_allow_the_guard.json"), "w") as f:
        json.dump(rows, f, indent=1)


if __name__ == "__main__":
    main()
