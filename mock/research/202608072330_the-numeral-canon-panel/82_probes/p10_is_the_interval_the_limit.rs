// PROBE p10. Attacking p2's result from the direction that would weaken it most.
//
// p2 established that over INTERVALS, `LO >= 0 || HI <= 0` matches associativity
// on the generated closure exactly. But an interval is only one shape a declared
// operand set can take, and op's steer at 83 says a predicate may read any
// const-available data, not only an interval's two bounds. So a richer
// declaration language is admissible, and the obvious attack is:
//
//   is there a STRADDLING operand set, of any shape, on which signed saturating
//   addition is associative over its closure?
//
// If yes, p2's predicate is exact for intervals and too narrow in general, and a
// design offering set-valued declarations would license strictly more. If no,
// sign uniformity is necessary for every declared operand set whatsoever, which
// is a much stronger statement than p2 measured and means no richer declaration
// language buys anything on this law.
//
// Exhaustive over EVERY subset of the representable set at widths 2, 3 and 4
// (that is 4, 256 and 65,536 subsets), and over a large seeded sample at widths
// 5 and 6 where exhaustive is out of reach. The empty set and the singleton {0}
// are included and reported separately, since both are trivially associative and
// would otherwise inflate the counts.

fn sat_add(x: i32, y: i32, minv: i32, maxv: i32) -> i32 {
    let s = x + y;
    if s > maxv {
        maxv
    } else if s < minv {
        minv
    } else {
        s
    }
}

/// The subsemigroup generated by a set, as a bitmask over the representable set.
fn closure_mask(mut mask: u64, minv: i32, maxv: i32, n: usize) -> u64 {
    loop {
        let mut added = mask;
        for i in 0..n {
            if mask >> i & 1 == 0 {
                continue;
            }
            for j in 0..n {
                if mask >> j & 1 == 0 {
                    continue;
                }
                let z = sat_add(minv + i as i32, minv + j as i32, minv, maxv);
                added |= 1u64 << ((z - minv) as usize);
            }
        }
        if added == mask {
            return mask;
        }
        mask = added;
    }
}

fn associative_on_mask(mask: u64, minv: i32, maxv: i32, n: usize) -> bool {
    for i in 0..n {
        if mask >> i & 1 == 0 {
            continue;
        }
        let a = minv + i as i32;
        for j in 0..n {
            if mask >> j & 1 == 0 {
                continue;
            }
            let b = minv + j as i32;
            for k in 0..n {
                if mask >> k & 1 == 0 {
                    continue;
                }
                let c = minv + k as i32;
                if sat_add(sat_add(a, b, minv, maxv), c, minv, maxv)
                    != sat_add(a, sat_add(b, c, minv, maxv), minv, maxv)
                {
                    return false;
                }
            }
        }
    }
    true
}

/// Does the set straddle zero, meaning it holds a strictly negative and a
/// strictly positive member? This is p2's predicate generalised from an
/// interval's two bounds to an arbitrary set.
fn straddles(mask: u64, minv: i32, n: usize) -> bool {
    let mut neg = false;
    let mut pos = false;
    for i in 0..n {
        if mask >> i & 1 == 0 {
            continue;
        }
        let v = minv + i as i32;
        if v < 0 {
            neg = true;
        }
        if v > 0 {
            pos = true;
        }
    }
    neg && pos
}

fn set_to_string(mask: u64, minv: i32, n: usize) -> String {
    let mut v: Vec<i32> = Vec::new();
    for i in 0..n {
        if mask >> i & 1 != 0 {
            v.push(minv + i as i32);
        }
    }
    format!("{:?}", v)
}

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }
}

fn main() {
    println!("p10: is sign uniformity necessary for EVERY declared operand set,");
    println!("     or only for intervals\n");

    println!("exhaustive over every subset of the representable set:\n");
    println!(
        "{:>5} {:>10} {:>14} {:>14} {:>22} {:>18}",
        "width", "subsets", "straddling", "assoc-closed", "STRADDLING AND ASSOC", "sign-unif & !assoc"
    );

    for w in 2u32..=4 {
        let maxv: i32 = (1i32 << (w - 1)) - 1;
        let minv: i32 = -(1i32 << (w - 1));
        let n = (maxv - minv + 1) as usize;
        let mut straddling = 0u64;
        let mut assoc = 0u64;
        let mut both = 0u64;
        let mut suff = 0u64;
        let mut witness: Option<String> = None;
        for mask in 1u64..(1u64 << n) {
            let cl = closure_mask(mask, minv, maxv, n);
            let a = associative_on_mask(cl, minv, maxv, n);
            let s = straddles(mask, minv, n);
            if s {
                straddling += 1;
            }
            if a {
                assoc += 1;
            }
            if s && a {
                both += 1;
                if witness.is_none() {
                    witness = Some(set_to_string(mask, minv, n));
                }
            }
            if !s && !a {
                suff += 1;
            }
        }
        println!(
            "{:>5} {:>10} {:>14} {:>14} {:>22} {:>18}",
            w,
            (1u64 << n) - 1,
            straddling,
            assoc,
            both,
            suff
        );
        if let Some(ws) = witness {
            println!("      WITNESS straddling AND associative on its closure: {}", ws);
        }
    }

    println!("\nsampled where exhaustive is out of reach. Sets are drawn by picking each");
    println!("value independently with probability one half, then resampled until the set");
    println!("straddles, so every sample is in the region the attack cares about.\n");
    println!(
        "{:>5} {:>16} {:>22} {:>16}",
        "width", "straddling sets", "of which assoc-closed", "control: assoc"
    );

    let mut rng = Rng(0xDEADBEEFCAFEF00D);
    for w in [5u32, 6u32] {
        let maxv: i32 = (1i32 << (w - 1)) - 1;
        let minv: i32 = -(1i32 << (w - 1));
        let n = (maxv - minv + 1) as usize;
        let mut drawn = 0u64;
        let mut assoc_straddling = 0u64;
        let mut assoc_any = 0u64;
        let mut tried = 0u64;
        while drawn < 400_000 && tried < 20_000_000 {
            tried += 1;
            let mut mask: u64 = 0;
            for i in 0..n {
                if rng.next() & 1 == 1 {
                    mask |= 1u64 << i;
                }
            }
            if mask == 0 {
                continue;
            }
            let cl = closure_mask(mask, minv, maxv, n);
            let a = associative_on_mask(cl, minv, maxv, n);
            if a {
                assoc_any += 1;
            }
            if !straddles(mask, minv, n) {
                continue;
            }
            drawn += 1;
            if a {
                assoc_straddling += 1;
                println!(
                    "      WITNESS at width {}: {} is straddling AND associative on its closure",
                    w,
                    set_to_string(mask, minv, n)
                );
            }
        }
        println!(
            "{:>5} {:>16} {:>22} {:>16}",
            w, drawn, assoc_straddling, assoc_any
        );
    }

    println!("\nsection 3: the control. If `associative_on_mask` could not return false");
    println!("the tables above would be meaningless. Two named sets, one of each kind:\n");
    let (minv, maxv, n) = (-8i32, 7i32, 16usize);
    for (label, vals) in [
        ("non-negative [0,7]", vec![0, 1, 2, 3, 4, 5, 6, 7]),
        ("straddling [-1,1]", vec![-1, 0, 1]),
        ("straddling multiples of 4", vec![-4, 0, 4]),
        ("non-positive [-7,0]", vec![-7, -6, -5, -4, -3, -2, -1, 0]),
        ("straddling sparse {-8, 7}", vec![-8, 7]),
    ] {
        let mut mask = 0u64;
        for v in &vals {
            mask |= 1u64 << ((v - minv) as usize);
        }
        let cl = closure_mask(mask, minv, maxv, n);
        println!(
            "  {:<28} straddles {:<6} closure size {:>3}  associative {}",
            label,
            straddles(mask, minv, n),
            (cl.count_ones()),
            associative_on_mask(cl, minv, maxv, n)
        );
    }

    println!("\nreading: column 5 of the first table is the attack. Zero there means no");
    println!("declared operand set of ANY shape, at that width, is both straddling and");
    println!("associative over its closure, so sign uniformity is necessary for every");
    println!("declaration and not only for intervals. Column 6 is the other direction:");
    println!("zero means every sign-uniform set is associative, which p2 measured for");
    println!("intervals and this extends to arbitrary sets.");
}
