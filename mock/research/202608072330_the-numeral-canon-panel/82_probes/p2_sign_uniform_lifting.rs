// PROBE p2. The second lifting route, and the one that is not about P4.
//
// p1 showed that lifting 79's P4 through declared ranges reaches only regions
// where no clamp can fire or where an operand is pinned to zero. The reason is
// visible in p1's own characterisation: the region P4 names is not closed under
// the operations it is a law about, so a declaration that implies it has to
// forbid the operations from leaving it, which means forbidding the clamp.
//
// So the question this probe asks is whether some OTHER measured trajectory
// predicate names a region that IS closed, and therefore lifts without
// forbidding the behaviour it is a law about.
//
// The candidate is the fold-associativity region for SIGNED saturating
// addition. Two facts already in the panel bracket it:
//
//   - 35 (via OPTIONS.md:1093-1096) measured that signed saturating folds
//     diverge under reassociation on 70.1% of vectors at n = 8, against 0% for
//     the other three sign-and-policy combinations.
//   - 55b (via OPTIONS.md:1117-1135) measured that of 952 divergent signed
//     triples, ZERO have all-same-sign operands, and that every divergence is a
//     clamp event followed by an operand moving the partial sum back toward the
//     interior.
//
// "All operands same sign" is a property of a DECLARED INTERVAL, not of a
// trajectory: an interval either straddles zero or it does not, and that is
// known at monomorphisation. So the lifting candidate is:
//
//   declared operand interval [LO, HI] with (LO >= 0 or HI <= 0)
//        implies
//   every parenthesisation of a fold over operands from [LO, HI] agrees.
//
// Both directions are measured, over every interval of the representable set,
// at every width in the model band, against brute force. The closure is
// computed rather than assumed, because the law is about a fold whose
// intermediates leave the declared interval.

// ---------------------------------------------------------------------------
// Signed saturating addition at a modelled width.
// ---------------------------------------------------------------------------

fn sat_add(x: i64, y: i64, minv: i64, maxv: i64) -> i64 {
    let s = x + y;
    if s > maxv {
        maxv
    } else if s < minv {
        minv
    } else {
        s
    }
}

// The subsemigroup generated by a declared interval: every value a fold over
// operands from [lo, hi] can ever hold, at any length. Computed to a fixpoint,
// not assumed.
fn closure(lo: i64, hi: i64, minv: i64, maxv: i64) -> Vec<i64> {
    let mut present = vec![false; (maxv - minv + 1) as usize];
    let idx = |v: i64| (v - minv) as usize;
    let mut work: Vec<i64> = Vec::new();
    for v in lo..=hi {
        if !present[idx(v)] {
            present[idx(v)] = true;
            work.push(v);
        }
    }
    let mut i = 0;
    while i < work.len() {
        let x = work[i];
        i += 1;
        let snapshot: Vec<i64> = work.clone();
        for &y in snapshot.iter() {
            for &(p, q) in [(x, y), (y, x)].iter() {
                let z = sat_add(p, q, minv, maxv);
                if !present[idx(z)] {
                    present[idx(z)] = true;
                    work.push(z);
                }
            }
        }
    }
    let mut out: Vec<i64> = (minv..=maxv).filter(|v| present[idx(*v)]).collect();
    out.sort_unstable();
    out
}

// Associativity of the operation restricted to a set.
fn associative_on(set: &[i64], minv: i64, maxv: i64) -> bool {
    for &a in set {
        for &b in set {
            for &c in set {
                let l = sat_add(sat_add(a, b, minv, maxv), c, minv, maxv);
                let r = sat_add(a, sat_add(b, c, minv, maxv), minv, maxv);
                if l != r {
                    return false;
                }
            }
        }
    }
    true
}

// Every parenthesisation of a chain, computed directly rather than assumed to
// follow from arity 3. Returns the set of distinct results.
fn all_parenthesisations(xs: &[i64], minv: i64, maxv: i64) -> Vec<i64> {
    if xs.len() == 1 {
        return vec![xs[0]];
    }
    let mut out: Vec<i64> = Vec::new();
    for split in 1..xs.len() {
        let left = all_parenthesisations(&xs[..split], minv, maxv);
        let right = all_parenthesisations(&xs[split..], minv, maxv);
        for &l in &left {
            for &r in &right {
                let v = sat_add(l, r, minv, maxv);
                if !out.contains(&v) {
                    out.push(v);
                }
            }
        }
    }
    out
}

// The candidate const predicate. A function of the declaration alone.
fn sign_uniform(lo: i64, hi: i64) -> bool {
    lo >= 0 || hi <= 0
}

fn main() {
    println!("p2: does the fold-associativity region lift through a declared interval\n");

    // -----------------------------------------------------------------------
    // Section 1: over EVERY interval of the representable set, at each model
    // width, compare the candidate predicate against brute-force associativity
    // on the interval's closure. Both directions counted.
    // -----------------------------------------------------------------------
    println!("section 1: sign_uniform(LO, HI) against associativity on the generated closure");
    println!(
        "{:>5} {:>10} {:>12} {:>14} {:>14} {:>14}",
        "width", "intervals", "assoc-closed", "sign-uniform", "suff. viol.", "nec. viol."
    );
    for w in 2u32..=6 {
        let maxv: i64 = (1i64 << (w - 1)) - 1;
        let minv: i64 = -(1i64 << (w - 1));
        let mut intervals: u64 = 0;
        let mut assoc_count: u64 = 0;
        let mut pred_count: u64 = 0;
        let mut suff: u64 = 0; // predicate true, law false
        let mut nec: u64 = 0; // predicate false, law true
        let mut first_suff: Option<(i64, i64)> = None;
        let mut first_nec: Option<(i64, i64)> = None;
        for lo in minv..=maxv {
            for hi in lo..=maxv {
                intervals += 1;
                let c = closure(lo, hi, minv, maxv);
                let assoc = associative_on(&c, minv, maxv);
                let pred = sign_uniform(lo, hi);
                if assoc {
                    assoc_count += 1;
                }
                if pred {
                    pred_count += 1;
                }
                if pred && !assoc {
                    suff += 1;
                    if first_suff.is_none() {
                        first_suff = Some((lo, hi));
                    }
                }
                if !pred && assoc {
                    nec += 1;
                    if first_nec.is_none() {
                        first_nec = Some((lo, hi));
                    }
                }
            }
        }
        println!(
            "{:>5} {:>10} {:>12} {:>14} {:>14} {:>14}",
            w, intervals, assoc_count, pred_count, suff, nec
        );
        if first_suff.is_some() || first_nec.is_some() {
            println!(
                "      first sufficiency violation {:?}, first necessity violation {:?}",
                first_suff, first_nec
            );
        }
    }

    // -----------------------------------------------------------------------
    // Section 1b: NEGATIVE CONTROL. Two plausible-looking weakenings of the
    // predicate. If the instrument cannot fail, these must still report zero,
    // which would mean section 1 proves nothing.
    // -----------------------------------------------------------------------
    println!("\nsection 1b: negative control, weakened predicates over widths 2..=5");
    let mutants: [(&str, fn(i64, i64) -> bool); 4] = [
        (
            "M1: LO >= -1 || HI <= 0   (allow one negative)",
            |lo, hi| lo >= -1 || hi <= 0,
        ),
        (
            "M2: LO >= 0 || HI <= 1    (allow one positive)",
            |lo, hi| lo >= 0 || hi <= 1,
        ),
        (
            "M3: LO >= 0               (drop the non-positive arm)",
            |lo, _hi| lo >= 0,
        ),
        (
            "M4: HI - LO <= 1          (narrow interval, any sign)",
            |lo, hi| hi - lo <= 1,
        ),
    ];
    for (name, mutant) in mutants.iter() {
        let mut suff: u64 = 0;
        let mut nec: u64 = 0;
        for w in 2u32..=5 {
            let maxv: i64 = (1i64 << (w - 1)) - 1;
            let minv: i64 = -(1i64 << (w - 1));
            for lo in minv..=maxv {
                for hi in lo..=maxv {
                    let c = closure(lo, hi, minv, maxv);
                    let assoc = associative_on(&c, minv, maxv);
                    let pred = mutant(lo, hi);
                    if pred && !assoc {
                        suff += 1;
                    }
                    if !pred && assoc {
                        nec += 1;
                    }
                }
            }
        }
        println!("  {} -> sufficiency {} necessity {}", name, suff, nec);
    }

    // -----------------------------------------------------------------------
    // Section 2: the lifting has to survive arity, since a fold is not arity 3.
    // Every parenthesisation, computed directly, over operands drawn from a
    // sign-uniform interval and from a straddling one of the same size.
    // -----------------------------------------------------------------------
    println!("\nsection 2: every parenthesisation, arity 2..=5, computed not assumed");
    for w in [4u32, 5u32] {
        let maxv: i64 = (1i64 << (w - 1)) - 1;
        let minv: i64 = -(1i64 << (w - 1));
        let cases: [(&str, i64, i64); 4] = [
            ("full range (straddles)", minv, maxv),
            ("non-negative half", 0, maxv),
            ("non-positive half", minv, 0),
            ("narrow straddle [-1, 1]", -1, 1),
        ];
        for (label, lo, hi) in cases.iter() {
            let mut row = format!("  w={} {:<24}", w, label);
            for n in 2usize..=5 {
                let vals: Vec<i64> = (*lo..=*hi).collect();
                let mut total: u64 = 0;
                let mut diverge: u64 = 0;
                let mut idx = vec![0usize; n];
                loop {
                    let xs: Vec<i64> = idx.iter().map(|&i| vals[i]).collect();
                    let results = all_parenthesisations(&xs, minv, maxv);
                    total += 1;
                    if results.len() > 1 {
                        diverge += 1;
                    }
                    // odometer
                    let mut k = n;
                    loop {
                        if k == 0 {
                            break;
                        }
                        k -= 1;
                        idx[k] += 1;
                        if idx[k] < vals.len() {
                            break;
                        }
                        idx[k] = 0;
                        if k == 0 {
                            break;
                        }
                    }
                    if idx.iter().all(|&i| i == 0) {
                        break;
                    }
                }
                row.push_str(&format!(" n={}:{}/{}", n, diverge, total));
            }
            println!("{}", row);
        }
    }

    // -----------------------------------------------------------------------
    // Section 3: the payoff, in the shape 35 measured it. A fold of length 8 at
    // a shipped width, sampled, comparing a left fold against a balanced tree,
    // for the full declared range and for the non-negative declared range.
    // -----------------------------------------------------------------------
    println!(
        "\nsection 3: length-8 fold, left against balanced tree, width 8 signed, 4,000,000 samples"
    );
    let maxv: i64 = 127;
    let minv: i64 = -128;
    let mut state: u64 = 0x243F6A8885A308D3;
    let mut next = move || {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        state
    };
    let left_fold = |xs: &[i64]| -> i64 {
        let mut acc = xs[0];
        for &x in &xs[1..] {
            acc = sat_add(acc, x, minv, maxv);
        }
        acc
    };
    let tree_fold = |xs: &[i64]| -> i64 {
        let mut cur: Vec<i64> = xs.to_vec();
        while cur.len() > 1 {
            let mut nxt: Vec<i64> = Vec::new();
            let mut i = 0;
            while i + 1 < cur.len() {
                nxt.push(sat_add(cur[i], cur[i + 1], minv, maxv));
                i += 2;
            }
            if i < cur.len() {
                nxt.push(cur[i]);
            }
            cur = nxt;
        }
        cur[0]
    };

    let samples = 4_000_000u64;
    for (label, lo, hi) in [
        ("declared [-128, 127] (straddles)", -128i64, 127i64),
        ("declared [0, 127] (non-negative)", 0i64, 127i64),
        ("declared [-128, 0] (non-positive)", -128i64, 0i64),
        ("declared [-1, 127] (straddles by one)", -1i64, 127i64),
    ] {
        let span = (hi - lo + 1) as u64;
        let mut diverge: u64 = 0;
        let mut witness: Option<(Vec<i64>, i64, i64)> = None;
        for _ in 0..samples {
            let mut xs = [0i64; 8];
            for x in xs.iter_mut() {
                *x = lo + (next() % span) as i64;
            }
            let l = left_fold(&xs);
            let t = tree_fold(&xs);
            if l != t {
                diverge += 1;
                if witness.is_none() {
                    witness = Some((xs.to_vec(), l, t));
                }
            }
        }
        println!(
            "  {:<36} divergent {:>9} of {} ({:.4}%)",
            label,
            diverge,
            samples,
            100.0 * diverge as f64 / samples as f64
        );
        if let Some((xs, l, t)) = witness {
            println!("      witness {:?} left={} tree={}", xs, l, t);
        }
    }

    // -----------------------------------------------------------------------
    // Section 4: is the declaration CLOSED under the operation? This is the
    // property p1's route lacked. Reported as the reachable set's own bounds.
    // -----------------------------------------------------------------------
    println!("\nsection 4: closure of a declared interval under the operation, width 6 signed");
    let maxv: i64 = 31;
    let minv: i64 = -32;
    for (label, lo, hi) in [
        ("[0, 7] non-negative", 0i64, 7i64),
        ("[-7, 0] non-positive", -7i64, 0i64),
        ("[-1, 1] straddles", -1i64, 1i64),
        ("[3, 5] non-negative", 3i64, 5i64),
        ("[-2, 9] straddles", -2i64, 9i64),
    ] {
        let c = closure(lo, hi, minv, maxv);
        let assoc = associative_on(&c, minv, maxv);
        println!(
            "  {} declared [{}, {}] -> closure [{}, {}] size {} : sign-uniform closure {} : associative {}",
            label,
            lo,
            hi,
            c.first().unwrap(),
            c.last().unwrap(),
            c.len(),
            *c.first().unwrap() >= 0 || *c.last().unwrap() <= 0,
            assoc
        );
    }
}
