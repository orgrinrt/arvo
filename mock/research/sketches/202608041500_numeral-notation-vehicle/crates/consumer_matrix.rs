//! WORKS test: the whole-matrix round-trip this design owes rather than a
//! sample (`bench-and-sketch-discipline.md`, `catalogue-edge-cases-as-tests.md`).
//! Every case asserts `<raw_bias!(v) as Bias>::NUM/DEN == v`, read back
//! through the type-level `Pos::VAL`, not merely "it compiled." Two shapes
//! of coverage, not one: hand-picked boundary and near-miss cases (the
//! brief's own 37/38/83 example, sign, rationals, decimals, powers of two),
//! PLUS an exhaustively generated block covering EVERY three-digit decimal
//! magnitude (100 through 999, 900 cases, no sampling) so at least one
//! meaningful sub-range of the domain is asserted in full rather than
//! spot-checked. The domain itself is unbounded by design (the ratified
//! intent, 58:626), so "the whole matrix" here means every dimension that
//! could independently break gets covered, and the one dimension that is
//! itself finite and small enough to enumerate (three-digit magnitudes)
//! is enumerated completely rather than sampled from.

#[path = "tower.rs"]
mod tower;
use tower::*;

extern crate numeral_pm;
use numeral_pm::raw_bias;

macro_rules! assert_val {
    ($t:ty, $num:expr, $den:expr) => {
        assert_eq!(
            <$t as Bias>::NUM,
            $num,
            "NUM mismatch for {}",
            stringify!($t)
        );
        assert_eq!(
            <$t as Bias>::DEN,
            $den,
            "DEN mismatch for {}",
            stringify!($t)
        );
    };
}

