#!/usr/bin/env python3
# Generates a base-ten structural magnitude: digits, carry-threaded addition,
# reversal (so the stored form can be big-endian and read in order), a decimal
# to binary conversion, and the a133 container ladder running on the binary form.
# No feature gates, no flags.
import sys

out = []
w = out.append

w("// GENERATED by gen_dec.py. Base-ten structural magnitude with the a133 ladder.")
w("#![no_std]")
w("use core::marker::PhantomData;")
w("")
w("pub struct End;")
for d in range(10):
    w(f"pub struct N{d}<T>(PhantomData<T>);")
w("")
w("pub struct C0; pub struct C1;")
w("")

# ---- value read, little-endian: V(Nd<T>) = d + 10 * V(T)
w("pub trait Dec { const V: u32; }")
w("impl Dec for End { const V: u32 = 0; }")
for d in range(10):
    w(f"impl<T: Dec> Dec for N{d}<T> {{ const V: u32 = {d} + 10 * T::V; }}")
w("")

# ---- IncBy
w("pub trait IncBy<Cin> { type O; }")
w("impl IncBy<C0> for End { type O = End; }")
w("impl IncBy<C1> for End { type O = N1<End>; }")
for d in range(10):
    w(f"impl<T> IncBy<C0> for N{d}<T> {{ type O = N{d}<T>; }}")
for d in range(10):
    if d < 9:
        w(f"impl<T> IncBy<C1> for N{d}<T> {{ type O = N{d+1}<T>; }}")
    else:
        w("impl<T: IncBy<C1>> IncBy<C1> for N9<T> { type O = N0<<T as IncBy<C1>>::O>; }")
w("")

# ---- AddC, little-endian, carry threaded
w("pub trait AddC<R, Cin> { type O; }")
w("impl AddC<End, C0> for End { type O = End; }")
w("impl AddC<End, C1> for End { type O = N1<End>; }")
for d in range(10):
    for c in ("C0", "C1"):
        w(f"impl<T: IncBy<{c}>> AddC<N{d}<T>, {c}> for End "
          f"{{ type O = <N{d}<T> as IncBy<{c}>>::O; }}")
for d in range(10):
    for c in ("C0", "C1"):
        w(f"impl<T: IncBy<{c}>> AddC<End, {c}> for N{d}<T> "
          f"{{ type O = <N{d}<T> as IncBy<{c}>>::O; }}")
for a in range(10):
    for b in range(10):
        for cin, cv in (("C0", 0), ("C1", 1)):
            t = a + b + cv
            s, cout = t % 10, ("C1" if t >= 10 else "C0")
            w(f"impl<A: AddC<B, {cout}>, B> AddC<N{b}<B>, {cin}> for N{a}<A> "
              f"{{ type O = N{s}<<A as AddC<B, {cout}>>::O>; }}")
w("")
w("pub trait AddLe<R> { type O; }")
w("impl<L: AddC<R, C0>, R> AddLe<R> for L { type O = <L as AddC<R, C0>>::O; }")
w("")

# ---- reversal, so the stored form can be big-endian
w("pub trait RevA<Acc> { type O; }")
w("impl<Acc> RevA<Acc> for End { type O = Acc; }")
for d in range(10):
    w(f"impl<T: RevA<N{d}<Acc>>, Acc> RevA<Acc> for N{d}<T> "
      f"{{ type O = <T as RevA<N{d}<Acc>>>::O; }}")
w("pub type Rev<X> = <X as RevA<End>>::O;")
w("")
w("// big-endian addition: reverse, add little-endian, reverse back.")
w("pub trait Add<R> { type O; }")
w("impl<L, R> Add<R> for L")
w("where L: RevA<End>, R: RevA<End>,")
w("      <L as RevA<End>>::O: AddC<<R as RevA<End>>::O, C0>,")
w("      <<L as RevA<End>>::O as AddC<<R as RevA<End>>::O, C0>>::O: RevA<End>,")
w("{ type O = <<<L as RevA<End>>::O as AddC<<R as RevA<End>>::O, C0>>::O as RevA<End>>::O; }")
w("")
w("// big-endian value read, through the reversal")
w("pub trait Val { const V: u32; }")
w("impl<X: RevA<End>> Val for X where <X as RevA<End>>::O: Dec "
  "{ const V: u32 = <<X as RevA<End>>::O as Dec>::V; }")
w("")

# ---- binary tower and the a133 ladder
w("pub struct Z0<T>(PhantomData<T>); pub struct Z1<T>(PhantomData<T>); pub struct BEnd;")
w("pub trait Bin { const V: u32; }")
w("impl Bin for BEnd { const V: u32 = 0; }")
w("impl<T: Bin> Bin for Z0<T> { const V: u32 = 2 * T::V; }")
w("impl<T: Bin> Bin for Z1<T> { const V: u32 = 2 * T::V + 1; }")
w("pub trait BInc { type O; }")
w("impl BInc for BEnd { type O = Z1<BEnd>; }")
w("impl<T> BInc for Z0<T> { type O = Z1<T>; }")
w("impl<T: BInc> BInc for Z1<T> { type O = Z0<<T as BInc>::O>; }")
w("pub trait BDec { type O; }")
w("impl<T> BDec for Z1<T> { type O = Z0<T>; }")
w("impl<T: BDec> BDec for Z0<T> { type O = Z1<<T as BDec>::O>; }")
w("pub trait BAdd<R> { type O; }")
w("impl BAdd<BEnd> for BEnd { type O = BEnd; }")
w("impl<B> BAdd<Z0<B>> for BEnd { type O = Z0<B>; }")
w("impl<B> BAdd<Z1<B>> for BEnd { type O = Z1<B>; }")
w("impl<A> BAdd<BEnd> for Z0<A> { type O = Z0<A>; }")
w("impl<A> BAdd<BEnd> for Z1<A> { type O = Z1<A>; }")
w("impl<A: BAdd<B>, B> BAdd<Z0<B>> for Z0<A> { type O = Z0<<A as BAdd<B>>::O>; }")
w("impl<A: BAdd<B>, B> BAdd<Z1<B>> for Z0<A> { type O = Z1<<A as BAdd<B>>::O>; }")
w("impl<A: BAdd<B>, B> BAdd<Z0<B>> for Z1<A> { type O = Z1<<A as BAdd<B>>::O>; }")
w("impl<A: BAdd<B>, B> BAdd<Z1<B>> for Z1<A> where <A as BAdd<B>>::O: BInc "
  "{ type O = Z0<<<A as BAdd<B>>::O as BInc>::O>; }")
w("")
w("// decimal (little-endian) to binary: bin(Nd<T>) = lit(d) + 10 * bin(T)")
w("// and 10x = 8x + 2x, both shifts in the binary tower.")
lits = {}
for d in range(10):
    if d == 0:
        lits[d] = "BEnd"
    else:
        bits = bin(d)[2:][::-1]
        s = "BEnd"
        for ch in reversed(bits):
            s = ("Z1<" if ch == '1' else "Z0<") + s + ">"
        lits[d] = s
for d in range(10):
    w(f"pub type Lit{d} = {lits[d]};")
w("pub trait ToBin { type B; }")
w("impl ToBin for End { type B = BEnd; }")
for d in range(10):
    w(f"impl<T: ToBin> ToBin for N{d}<T>")
    w(f"where Z0<Z0<Z0<<T as ToBin>::B>>>: BAdd<Z0<<T as ToBin>::B>>,")
    w(f"      Lit{d}: BAdd<<Z0<Z0<Z0<<T as ToBin>::B>>> as BAdd<Z0<<T as ToBin>::B>>>::O>,")
    w(f"{{ type B = <Lit{d} as BAdd<<Z0<Z0<Z0<<T as ToBin>::B>>> "
      f"as BAdd<Z0<<T as ToBin>::B>>>::O>>::O; }}")
w("")

with open(sys.argv[1], "w") as f:
    f.write("\n".join(out) + "\n")
print(f"{len(out)} lines")
