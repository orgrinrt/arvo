//! Probe 5: multiplication IS closed over biased numerals, and the closure
//! formula generalises the exact-product rule the multiplicative half already
//! ships rather than replacing it.
//!
//! The consolidation records the closure gap as open with two candidate fixes:
//! "a general rational-adjustment constructor or a `MulClosed` condition with
//! explicit renormalisation" (`26_consolidation_two.md:326-331`), on the
//! reasoning that "a biased numeral's product generates cross terms". File 28
//! proposes the rational-pair adjustment (`28:319-328`), which addresses the
//! adjustment half and says nothing about the bias half.
//!
//! The cross terms are real and they are not an obstruction. For values
//! `v1 = A1*k1 + B1` and `v2 = A2*k2 + B2`,
//!
//!   v1*v2 = (A1*A2)*k1*k2 + (A1*B2)*k1 + (A2*B1)*k2 + B1*B2
//!
//! and every term but the last is in the lattice generated by `A1*A2`,
//! `A1*B2` and `A2*B1`. So the whole product set lies in
//!
//!   adjustment  L = gcd(A1*A2, A1*B2, A2*B1)
//!   bias        B1*B2
//!
//! which is a numeral of exactly the existing shape. With both biases zero,
//! `L = gcd(A1*A2, 0, 0) = A1*A2` and the bias is zero, which is "widths add,
//! quanta multiply" unchanged. The gcd is a type-level computation over the
//! adjustment representation, so it needs whatever that representation is
//! (file 28's rational pair for the `FullRange` case) and nothing else.
//!
//! Everything here is integer-scaled: a rational quantum `a = p/q` is carried
//! as `A = a * D` for a common denominator `D`, and the product then lives at
//! scale `D^2`, which changes the bookkeeping and not the formula.
//!
//! Every claim is a `const` assertion; compiling is the check.

#![no_std]

const fn gcd(a: i64, b: i64) -> i64 {
    let mut x = if a < 0 { -a } else { a };
    let mut y = if b < 0 { -b } else { b };
    while y != 0 {
        let t = x % y;
        x = y;
        y = t;
    }
    x
}

const fn gcd3(a: i64, b: i64, c: i64) -> i64 {
    gcd(gcd(a, b), c)
}

/// The closure formula, stated once and used by every claim below.
const fn product_adjustment(a1: i64, b1: i64, a2: i64, b2: i64) -> i64 {
    gcd3(a1 * a2, a1 * b2, a2 * b1)
}
const fn product_bias(b1: i64, b2: i64) -> i64 {
    b1 * b2
}

/// Every product of the two windows lands on the derived numeral's grid.
/// `k` ranges over `0..=kmax` for each operand, which is the whole window.
const fn every_product_is_on_the_derived_grid(
    a1: i64,
    b1: i64,
    k1max: i64,
    a2: i64,
    b2: i64,
    k2max: i64,
) -> bool {
    let la = product_adjustment(a1, b1, a2, b2);
    let lb = product_bias(b1, b2);
    let mut k1 = 0;
    while k1 <= k1max {
        let v1 = a1 * k1 + b1;
        let mut k2 = 0;
        while k2 <= k2max {
            let v2 = a2 * k2 + b2;
            let p = v1 * v2;
            if (p - lb) % la != 0 {
                return false;
            }
            k2 += 1;
        }
        k1 += 1;
    }
    true
}

// ---- the biased case, which the consolidation calls not closed ------------

const A1: i64 = 4;
const B1: i64 = 2; // values 2, 6, 10, 14
const A2: i64 = 6;
const B2: i64 = 4; // values 4, 10, 16, 22

const _: () = assert!(product_adjustment(A1, B1, A2, B2) == 4); // gcd(24, 16, 12)
const _: () = assert!(product_bias(B1, B2) == 8);
const _: () = assert!(every_product_is_on_the_derived_grid(A1, B1, 3, A2, B2, 3));

/// A second biased pair with no common factor arranged, so the first is not
/// an accident of the numbers chosen.
const _: () = assert!(every_product_is_on_the_derived_grid(7, 3, 5, 11, 5, 5));
const _: () = assert!(every_product_is_on_the_derived_grid(9, 15, 6, 21, 6, 6));
const _: () = assert!(every_product_is_on_the_derived_grid(1, 1, 9, 1, 1, 9));

/// MATLAB's own worked shape: a slope-and-bias fixed-point pair. Scaled by
/// 1000 so a slope of 0.125 and a bias of 0.375 are integers.
const _: () = assert!(every_product_is_on_the_derived_grid(
    125, 375, 7, 250, 500, 7
));

// ---- the unbiased case falls out, unchanged --------------------------------

/// With both biases zero the formula returns exactly "quanta multiply", so
/// the multiplicative half's verified adder is the special case rather than a
/// separate rule that has to agree with this one.
const _: () = assert!(product_adjustment(8, 0, 32, 0) == 8 * 32);
const _: () = assert!(product_bias(0, 0) == 0);
const _: () = assert!(every_product_is_on_the_derived_grid(8, 0, 15, 32, 0, 15));

/// One-sided bias, which is the shape a scale-and-offset conversion produces
/// when only one operand carries an offset.
const _: () = assert!(product_adjustment(8, 0, 6, 4) == gcd3(48, 32, 0));
const _: () = assert!(every_product_is_on_the_derived_grid(8, 0, 7, 6, 4, 7));

// ---- what the formula does NOT claim ---------------------------------------
//
// It does not claim the derived adjustment is the FINEST numeral containing
// the product set, only that it contains it, which is what closure needs and
// is the safe direction: a finer quantum than necessary wastes bits and a
// coarser one loses values. Tightness is an optimisation question and is
// checked here to be non-vacuous only in the sense that the products are not
// all equal.
const fn products_are_not_all_equal(a1: i64, b1: i64, a2: i64, b2: i64) -> bool {
    (a1 * 1 + b1) * (a2 * 1 + b2) != (a1 * 0 + b1) * (a2 * 0 + b2)
}
const _: () = assert!(products_are_not_all_equal(A1, B1, A2, B2));

