// Probe: bridging the ergonomic literal surface (`const N: u16`) to the
// type-level binary numeral from probe 03. This is the ergonomic cost the
// mechanism actually pays: a bounded, macro-generated per-N dispatch table,
// the same shape arvo already ships for strategy/container selection
// (`BitsContainerFor`'s Pattern C const-tag dispatch). Widths beyond the
// generated bound do not compile; the bound is a macro-expansion parameter,
// not a design limit.
#![allow(dead_code)]

use core::marker::PhantomData;

pub trait Bit {
    const VAL: u16;
}
pub struct B0;
pub struct B1;
impl Bit for B0 {
    const VAL: u16 = 0;
}
impl Bit for B1 {
    const VAL: u16 = 1;
}

pub trait Width {
    const VALUE: u16;
}
pub struct UTerm;
pub struct UInt<Hi, Lo>(PhantomData<(Hi, Lo)>);
impl Width for UTerm {
    const VALUE: u16 = 0;
}
impl<Hi: Width, Lo: Bit> Width for UInt<Hi, Lo> {
    const VALUE: u16 = Hi::VALUE * 2 + Lo::VAL;
}

// the bridge: one impl PER LITERAL N. Table-shaped (section 11's "impl-per-
// row" case), not projection-shaped; kept here to a small bound to prove the
// mechanism, generated by macro so the real bound is a one-line change.
pub trait LiteralWidth<const N: u16> {
    type W: Width;
}
pub struct Lit;

macro_rules! literal_widths {
    ($($n:literal => $ty:ty),* $(,)?) => {
        $(
            impl LiteralWidth<$n> for Lit {
                type W = $ty;
            }
        )*
    };
}

literal_widths! {
    0  => UTerm,
    1  => UInt<UTerm, B1>,
    2  => UInt<UInt<UTerm, B1>, B0>,
    3  => UInt<UInt<UTerm, B1>, B1>,
    4  => UInt<UInt<UInt<UTerm, B1>, B0>, B0>,
    5  => UInt<UInt<UInt<UTerm, B1>, B0>, B1>,
    6  => UInt<UInt<UInt<UTerm, B1>, B1>, B0>,
    7  => UInt<UInt<UInt<UTerm, B1>, B1>, B1>,
    13 => UInt<UInt<UInt<UInt<UTerm, B1>, B1>, B0>, B1>,
    20 => UInt<UInt<UInt<UInt<UInt<UTerm, B1>, B0>, B1>, B0>, B0>,
}

// the consumer-facing alias shape: `Ufixed<13, 3>` reads as literal sugar,
// resolves through the bridge to the typed numeral used by AddWidth.
pub type WidthOf<const N: u16> = <Lit as LiteralWidth<N>>::W;

const fn assert_eq_u16(a: u16, b: u16) {
    assert!(a == b);
}
const _: () = assert_eq_u16(WidthOf::<13>::VALUE, 13);
const _: () = assert_eq_u16(WidthOf::<7>::VALUE, 7);
const _: () = assert_eq_u16(WidthOf::<0>::VALUE, 0);

fn main() {
    println!("WidthOf<13> = {}", WidthOf::<13>::VALUE);
    println!("WidthOf<20> = {}", WidthOf::<20>::VALUE);
}
