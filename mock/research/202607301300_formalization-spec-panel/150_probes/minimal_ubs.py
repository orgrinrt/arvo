"""Minimal upper bounds in the unbiased radix-two slice, searched completely.

decisive.py uses a sufficient test: two upper bounds whose intersection is
exactly the union. It found nothing at radix two. That is not a proof of absence,
so this probe runs the stronger test 148 uses, with the search region bounded
explicitly rather than by an enumeration's incidental limits.

Value sets are held as (quantum, lo, hi) with the set being {k*q : lo <= k <= hi}
and the bias zero, which is the affine model with the phase fixed. Inclusion is
then arithmetic rather than set containment, which is what makes the wide search
affordable:

    (q1,l1,h1) inside (q2,l2,h2)  iff  m = q1/q2 is a positive integer
                                       and l2 <= l1*m and h1*m <= h2.

The region argument. Any upper bound's quantum divides the quantum the union
generates, and at radix two the admissible quanta are powers of two, so the
candidates are g/2^j. The probe walks j to J and reports whether the minimal set
is the same at J and at J+2. If it is not, it says so rather than concluding.
"""

from fractions import Fraction as Q
from itertools import combinations


def admissible_at(q, pmax):
    """(q, lo, hi) for every unbiased radix-two shape at quantum q."""
    out = []
    for p in range(0, pmax + 1):
        n = 2 ** p
        out.append((q, 0, n - 1))          # non-negative
        out.append((q, -(n - 1), n - 1))   # symmetric
        out.append((q, -n, n - 1))         # asymmetric low
    return out


def inside(a, b):
    (q1, l1, h1), (q2, l2, h2) = a, b
    m = q1 / q2
    if m.denominator != 1:
        return False
    m = m.numerator
    return l2 <= l1 * m and h1 * m <= h2


def hull_of(a, b):
    """Quantum generated by the union, and the union's index span at it."""
    (q1, l1, h1), (q2, l2, h2) = a, b
    g = Q(1, 1)
    # the generated quantum is the gcd of the two quanta (bias zero)
    n1, d1 = q1.numerator, q1.denominator
    n2, d2 = q2.numerator, q2.denominator
    from math import gcd
    g = Q(gcd(n1 * d2, n2 * d1), d1 * d2)
    lo = min(l1 * (q1 / g), l2 * (q2 / g))
    hi = max(h1 * (q1 / g), h2 * (q2 / g))
    return g, int(lo), int(hi)


def minimal_ubs(a, b, J, pmax=24):
    g, lo, hi = hull_of(a, b)
    cands = []
    for j in range(J + 1):
        q = g / (2 ** j)
        scale = 2 ** j
        for c in admissible_at(q, pmax):
            if c[1] <= lo * scale and hi * scale <= c[2]:
                cands.append(c)
    return [c for c in cands if not any(d != c and inside(d, c) for d in cands)]


def main():
    base = []
    for e in range(-4, 4):
        for p in range(0, 5):
            base += admissible_at(Q(2) ** e, p)
    base = sorted({c for c in base if c[2] > c[1]})

    multi = unstable = 0
    shown = 0
    for a, b in combinations(base, 2):
        m1 = minimal_ubs(a, b, J=8)
        m2 = minimal_ubs(a, b, J=10)
        if len(m1) != len(m2):
            unstable += 1
            continue
        if len(m1) > 1:
            multi += 1
            if shown < 5:
                shown += 1
                print(f"  {a} v {b}  ->  {len(m1)} minimal upper bounds: {m1}")
    print(f"\npairs {len(base)*(len(base)-1)//2}"
          f"   more than one minimal upper bound: {multi}"
          f"   region unstable J=8 vs J=10: {unstable}")
    if multi == 0 and unstable == 0:
        print("Every pair in the unbiased radix-two slice has exactly one "
              "minimal upper bound. The join exists throughout it.")


if __name__ == "__main__":
    main()
