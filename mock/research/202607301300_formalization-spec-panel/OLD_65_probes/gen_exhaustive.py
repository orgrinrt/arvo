#!/usr/bin/env python3
"""Emit probe_5: the bucket law asserted over EVERY width 1..=MAX, not a sample.

Reads probe_4's machinery verbatim (minus its own 13-point check) and appends
one assertion per width. The point is the review's own standing rule: a law
asserted over chosen instantiations is a decision about what not to find out.
"""
import sys
MAX = int(sys.argv[1]) if len(sys.argv) > 1 else 512
def pos(n):
    # H = 1, O<P> = 2P, Iv<P> = 2P+1; outermost constructor is the LSB.
    assert n >= 1
    if n == 1: return "H"
    return ("O<" if n % 2 == 0 else "Iv<") + pos(n // 2) + ">"
src = open("probe_4_bucket_machinery.rs").read()
src = src.split("// -- differential check")[0]
out = [src]
out.append("// -- differential check over EVERY width 1..=%d, generated by gen_exhaustive.py --\n" % MAX)
out.append("macro_rules! check { ($($t:ty),+ $(,)?) => { const _: () = { $(\n"
           "    assert!(<<$t as Bucket>::Out as Tag>::IDX == tag_hot_cold(<$t as Nat>::VAL as u16));\n"
           ")+ }; } }\n")
for n in range(1, MAX + 1):
    out.append("type W%d = Pz<%s>;\n" % (n, pos(n)))
out.append("check!(" + ", ".join("W%d" % n for n in range(1, MAX + 1)) + ");\n")
open("probe_5_bucket_exhaustive.rs", "w").write("".join(out))
print("wrote probe_5_bucket_exhaustive.rs for widths 1..=%d" % MAX)
